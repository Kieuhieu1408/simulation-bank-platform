package com.hieu.corebank.customer;

import com.hieu.corebank.customer.api.dto.request.CustomerCreateRequestDTO;
import com.hieu.corebank.customer.api.dto.response.CustomerResponseDTO;
import com.hieu.corebank.customer.application.command.CreateCustomerCommandHandler;
import com.hieu.corebank.shared.domain.ConflictException;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.test.context.ActiveProfiles;

import java.util.UUID;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

@SpringBootTest
@ActiveProfiles("test")
class CustomerCreationIntegrationTest {

    @Autowired
    private CreateCustomerCommandHandler createCustomerHandler;

    @Test
    @DisplayName("AC-CB-01: Tạo khách hàng mới tự động sinh mã CIF chuẩn 8 số duy nhất (00000001 - 99999999)")
    void testAutoGeneratedEightDigitCif() {
        String uniqueNationalId = "079" + String.format("%09d", Math.abs(UUID.randomUUID().hashCode() % 1_000_000_000L));
        CustomerCreateRequestDTO req = CustomerCreateRequestDTO.builder()
                .nationalId(uniqueNationalId)
                .fullName("Nguyen Van Test")
                .phoneNumber("0912345678")
                .email("test.cif@bank.com")
                .build();

        CustomerResponseDTO response = createCustomerHandler.handle(req.toCommand());

        assertThat(response).isNotNull();
        assertThat(response.getCifNumber()).isNotNull();
        // Mã CIF phải đúng 8 chữ số
        assertThat(response.getCifNumber()).matches("^[0-9]{8}$");
        // CCCD phải được che mờ dạng 012345****01
        assertThat(response.getNationalId()).isEqualTo(uniqueNationalId.substring(0, 6) + "****" + uniqueNationalId.substring(10));
    }

    @Test
    @DisplayName("AC-CB-01: Chặn tạo trùng CCCD qua Cấp 2 và Cấp 4 DB constraint (trả về Conflict)")
    void testPreventDuplicateNationalId() {
        String duplicateNationalId = "036" + String.format("%09d", Math.abs(UUID.randomUUID().hashCode() % 1_000_000_000L));
        CustomerCreateRequestDTO req1 = CustomerCreateRequestDTO.builder()
                .nationalId(duplicateNationalId)
                .fullName("Khach Hang Mot")
                .phoneNumber("0987654321")
                .email("kh1@bank.com")
                .build();

        CustomerResponseDTO res1 = createCustomerHandler.handle(req1.toCommand());
        assertThat(res1.getCifNumber()).isNotNull();

        // Request thứ 2 dùng cùng số CCCD
        CustomerCreateRequestDTO req2 = CustomerCreateRequestDTO.builder()
                .nationalId(duplicateNationalId)
                .fullName("Khach Hang Hai")
                .phoneNumber("0987654322")
                .email("kh2@bank.com")
                .build();

        assertThatThrownBy(() -> createCustomerHandler.handle(req2.toCommand()))
                .isInstanceOf(ConflictException.class)
                .hasMessageContaining("National ID already exists");
    }

    @Test
    @DisplayName("Hỗ trợ tạo khách hàng với số Hộ chiếu hợp lệ (NĐ 13/2023)")
    void testSupportValidPassport() {
        String passport = "B" + String.format("%07d", Math.abs(UUID.randomUUID().hashCode() % 10_000_000L));
        CustomerCreateRequestDTO req = CustomerCreateRequestDTO.builder()
                .nationalId(passport)
                .fullName("John Passport Doe")
                .phoneNumber("0934567890")
                .email("passport@bank.com")
                .build();

        CustomerResponseDTO res = createCustomerHandler.handle(req.toCommand());
        assertThat(res.getCifNumber()).matches("^[0-9]{8}$");
        assertThat(res.getNationalId()).isEqualTo(passport.substring(0, 2) + "****" + passport.substring(passport.length() - 2));
    }
}
